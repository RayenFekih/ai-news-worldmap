/** Emoji flag from an ISO 3166-1 alpha-2 code, via regional indicator symbols. */
function flagFromIso2(iso2: string): string {
  return iso2
    .toUpperCase()
    .replace(/./g, (char) => String.fromCodePoint(127397 + char.charCodeAt(0)));
}

export function resolveCountry(sourceCountry: string) {
  const name = sourceCountry?.trim();
  if (!name) return null;

  const entry = CENTROIDS[name] ?? CENTROIDS[ALIASES[name]];
  if (!entry) return null;

  return { lat: entry.lat, lng: entry.lng, iso2: entry.iso2, flag: flagFromIso2(entry.iso2) };
}
